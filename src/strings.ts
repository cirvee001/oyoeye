export type StrKey = keyof typeof STRINGS;
export type Params = Record<string, string | number>;

const fill = (s: string, p?: Params) => (p ? s.replace(/\{(\w+)\}/g, (_, k) => (p[k] != null ? String(p[k]) : `{${k}}`)) : s);

export function tr(key: StrKey, lang: Lang = 'en', p?: Params) {
  const pair = STRINGS[key] as readonly [string, string] | undefined;
  if (!pair) return key;
  return fill(pair[lang === 'yo' && pair[1] ? 1 : 0], p);
}

