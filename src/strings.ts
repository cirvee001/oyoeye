export type MsgKey = keyof typeof MSG;

export const msg = (k: MsgKey, p?: Msg['p']): Msg => ({ k, p });

export function msgText(m: Msg, lang: Lang = 'en'): string {
  const pair = MSG[m.k] as readonly [string, string] | undefined;
  if (!pair) return String(m.k);
  const base = pair[lang === 'yo' && pair[1] ? 1 : 0];
  return base.replace(/\{(\w+)\}/g, (_, k) => {
    const v = m.p?.[k];
    if (v == null) return '';
    if (typeof v === 'object') return msgText(v, lang);
    const s = String(v);
    if (s.startsWith('@')) {
      const key = s.slice(1);
      if (key in MSG) return msgText({ k: key as MsgKey }, lang);
      if (key in STRINGS) return tr(key as StrKey, lang);
    }
    return s;
  });
}

